-- Live verification fixtures are always rolled back. No provider calls or real refunds.
BEGIN;
DO $$
DECLARE
 own_user UUID; own_brand UUID; other_user UUID; other_brand UUID;
 res_id UUID; other_res UUID; result JSONB; blocked BOOLEAN; visible_count INTEGER;
 own_path TEXT; other_path TEXT;
BEGIN
 SELECT b.owner_id,b.id INTO own_user,own_brand FROM public.brands b JOIN public.profiles p ON p.id=b.owner_id WHERE NOT public.is_admin(b.owner_id) AND p.credit_balance>=2 LIMIT 1;
 SELECT b.owner_id,b.id INTO other_user,other_brand FROM public.brands b WHERE b.owner_id<>own_user AND NOT public.is_admin(b.owner_id) LIMIT 1;
 IF own_user IS NULL OR other_user IS NULL THEN RAISE EXCEPTION 'Verification needs two existing owners'; END IF;
 own_path := 'brands/'||own_brand||'/audit-verification/test.txt';
 other_path := 'brands/'||other_brand||'/audit-verification/test.txt';
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',own_user,'role','authenticated')::text,true);
 PERFORM set_config('request.jwt.claim.sub',own_user::text,true);
 EXECUTE 'SET LOCAL ROLE authenticated';
 IF NOT public.spark_can_access_storage_path(own_path) OR public.spark_can_access_storage_path(other_path) OR public.spark_can_access_storage_path('invalid/path') THEN RAISE EXCEPTION 'Storage path ownership failed'; END IF;
 INSERT INTO public.media_assets(storage_bucket,storage_path,file_type,uploaded_by)
 VALUES('Spark',other_path,'image',own_brand::text);
 IF public.spark_can_access_storage_path(other_path) THEN RAISE EXCEPTION 'Editable metadata granted cross-brand storage access'; END IF;
 INSERT INTO public.conversation_sessions(id,brand_id,user_id) VALUES('audit-rollback-session',own_brand::text,own_user);
 UPDATE public.conversation_sessions SET title='Verified update' WHERE id='audit-rollback-session';
 SELECT count(*) INTO visible_count FROM public.conversation_sessions WHERE id='audit-rollback-session' AND title='Verified update';
 IF visible_count<>1 THEN RAISE EXCEPTION 'Session owner CRUD failed'; END IF;
 INSERT INTO public.executive_sessions(brand_id) VALUES(own_brand) ON CONFLICT(brand_id) DO UPDATE SET last_screen='audit';
 INSERT INTO public.executive_director_summaries(brand_id) VALUES(own_brand) ON CONFLICT(brand_id) DO UPDATE SET mission='audit';
 INSERT INTO public.executive_timeline(brand_id,type) VALUES(own_brand,'AUDIT_ROLLBACK');
 INSERT INTO public.production_assets(id,brand_id,production_id,asset_type) VALUES('audit-rollback-asset',own_brand::text,'audit-rollback-production','image');
 blocked:=false;
 BEGIN INSERT INTO public.executive_timeline(brand_id,type) VALUES(other_brand,'AUDIT_ROLLBACK'); EXCEPTION WHEN insufficient_privilege THEN blocked:=true; END;
 IF NOT blocked THEN RAISE EXCEPTION 'Cross-brand insert was permitted'; END IF;
 INSERT INTO storage.objects(bucket_id,name) VALUES('Spark',own_path);
 UPDATE storage.objects SET metadata='{"audit":"rollback"}' WHERE bucket_id='Spark' AND name=own_path;
 SELECT count(*) INTO visible_count FROM storage.objects WHERE bucket_id='Spark' AND name=own_path;
 IF visible_count<>1 THEN RAISE EXCEPTION 'Owner storage select/upsert requirements failed'; END IF;
 blocked:=false;
 BEGIN INSERT INTO storage.objects(bucket_id,name) VALUES('Spark',other_path); EXCEPTION WHEN insufficient_privilege THEN blocked:=true; END;
 IF NOT blocked THEN RAISE EXCEPTION 'Cross-brand storage insert was permitted'; END IF;
 result := public.spark_reserve_credits(own_user,'audit-rollback-generation',2,'audit-rollback-key');
 res_id := (result->>'id')::uuid;
 result := public.spark_mark_pending_unknown(own_user,res_id,'audit rollback');
 IF result->>'status'<>'PENDING_UNKNOWN' THEN RAISE EXCEPTION 'Owner pending transition failed'; END IF;
 blocked:=false;
 BEGIN PERFORM public.spark_refund_credits(own_user,res_id,2,'audit-refund'); EXCEPTION WHEN raise_exception THEN blocked:=true; END;
 IF NOT blocked THEN RAISE EXCEPTION 'Ordinary user refund permitted'; END IF;
 EXECUTE 'RESET ROLE';
 INSERT INTO public.credit_reservations(user_id,generation_id,amount,status,idempotency_key) VALUES(other_user,'audit-other-generation',2,'RESERVED','audit-other-key') RETURNING id INTO other_res;
 EXECUTE 'SET LOCAL ROLE authenticated';
 blocked:=false;
 BEGIN PERFORM public.spark_mark_pending_unknown(own_user,other_res,'cross owner'); EXCEPTION WHEN raise_exception THEN blocked:=true; END;
 IF NOT blocked THEN RAISE EXCEPTION 'Cross-owner reservation mutation permitted'; END IF;
 blocked:=false;
 BEGIN PERFORM public.spark_reserve_credits(own_user,'audit-other-generation',2,'audit-other-key'); EXCEPTION WHEN raise_exception THEN blocked:=true; END;
 IF NOT blocked THEN RAISE EXCEPTION 'Cross-owner idempotency replay permitted'; END IF;
 EXECUTE 'RESET ROLE';
 PERFORM set_config('request.jwt.claims','{"role":"service_role"}',true);
 PERFORM set_config('request.jwt.claim.sub','',true);
 blocked:=false;
 BEGIN PERFORM public.spark_refund_credits(own_user,res_id,3,'audit-too-large'); EXCEPTION WHEN raise_exception THEN blocked:=true; END;
 IF NOT blocked THEN RAISE EXCEPTION 'Over-refund permitted'; END IF;
 blocked:=false;
 BEGIN PERFORM public.spark_refund_credits(own_user,other_res,2,'audit-wrong-owner'); EXCEPTION WHEN raise_exception THEN blocked:=true; END;
 IF NOT blocked THEN RAISE EXCEPTION 'Cross-owner refund permitted'; END IF;
 result:=public.spark_refund_credits(own_user,res_id,2,'audit-refund');
 IF result->>'status'<>'REFUNDED' THEN RAISE EXCEPTION 'Trusted refund failed'; END IF;
 result:=public.spark_refund_credits(own_user,res_id,2,'audit-refund');
 IF NOT (result->>'idempotent_replay')::boolean THEN RAISE EXCEPTION 'Refund replay failed'; END IF;
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',other_user,'role','authenticated')::text,true);
 PERFORM set_config('request.jwt.claim.sub',other_user::text,true);
 EXECUTE 'SET LOCAL ROLE authenticated';
 SELECT count(*) INTO visible_count FROM public.conversation_sessions WHERE id='audit-rollback-session';
 IF visible_count<>0 THEN RAISE EXCEPTION 'Cross-user session visible'; END IF;
 EXECUTE 'RESET ROLE';
 PERFORM set_config('request.jwt.claims','{"role":"anon"}',true);
 PERFORM set_config('request.jwt.claim.sub','',true);
 EXECUTE 'SET LOCAL ROLE anon';
 SELECT count(*) INTO visible_count FROM storage.objects WHERE bucket_id='Spark';
 IF visible_count<>0 THEN RAISE EXCEPTION 'Anonymous storage visibility'; END IF;
 blocked:=false;
 BEGIN INSERT INTO storage.objects(bucket_id,name) VALUES('Spark','audit-anon/test.txt'); EXCEPTION WHEN insufficient_privilege THEN blocked:=true; END;
 IF NOT blocked THEN RAISE EXCEPTION 'Anonymous storage write permitted'; END IF;
 EXECUTE 'RESET ROLE';
END $$;
ROLLBACK;
SELECT 'PASS: owner CRUD, cross-owner isolation, anonymous storage denial, credit ownership/cap/idempotency; all fixtures rolled back' AS verification;
